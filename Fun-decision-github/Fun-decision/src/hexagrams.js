export function lineBit(value) { return value === 7 || value === 9 ? 1 : 0; }
export function resolveHexagram(lines) {
  if (lines.length < 6) return null;
  const lower = lines.slice(0, 3).map(lineBit).join("");
  const upper = lines.slice(3, 6).map(lineBit).join("");
  return HEXAGRAMS[KING_WEN[TRIGRAM_INDEX[upper]][TRIGRAM_INDEX[lower]] - 1];
}
export function changedLines(lines) { return lines.map((value) => value === 6 ? 7 : value === 9 ? 8 : value); }
export function hexagramGlyph(number) { return String.fromCodePoint(0x4dc0 + number - 1); }

const TRIGRAM_BITS = Object.fromEntries(Object.entries(TRIGRAM_INDEX).map(([bits, index]) => [index, bits]));
/** Six line bits for a King Wen number, bottom line first (1 = yang, 0 = yin). */
export function hexagramLines(number) {
  for (let upper = 0; upper < 8; upper += 1) {
    const lower = KING_WEN[upper].indexOf(number);
    if (lower !== -1) return [...TRIGRAM_BITS[lower], ...TRIGRAM_BITS[upper]].map(Number);
  }
  return [1, 1, 1, 1, 1, 1];
}

